// Структура, в которой хранится разложение на простые множители
typedef struct Factors {
    int k;          // сколько различных простых в разложении
    int primes[32]; // различные простые в порядке возрастания
    int powers[32]; // в какие степени надо эти простые возводить
} Factors;

// Функция, которая находит разложение числа X и записывает его в структуру res
void Factorize(int X, Factors *res) {
    res->k = 0; // Изначально количество простых множителей равно 0
    
    if (X <= 1) {
        return; // Для 1 простых делителей нет
    }

    // Проверяем делители от 2 до корня из X
    for (int i = 2; i * i <= X; i++) {
        if (X % i == 0) {
            res->primes[res->k] = i; // Сохраняем найденный простой делитель
            res->powers[res->k] = 0;
            
            // Делим X на делитель, пока делится без остатка, и считаем степень
            while (X % i == 0) {
                res->powers[res->k]++;
                X /= i;
            }
            res->k++; // Переходим к следующему уникальному простому множителю
        }
    }
    
    // Если после всех делений X осталось больше 1, значит X само является простым числом
    if (X > 1) {
        res->primes[res->k] = X;
        res->powers[res->k] = 1;
        res->k++;
    }
}